def main() -> int:
    if not PROMPT_PATH.exists():
        print(f"FATAL: prompt not found at {PROMPT_PATH}", file=sys.stderr)
        return 2

    prompt_text = PROMPT_PATH.read_text(encoding="utf-8")
    issues = validate_prompt(prompt_text)
    print("[validate] v2.md structure:")
    if issues:
        for line in issues:
            print(f"  ! {line}")
        print("FATAL: prompt structure validation failed.", file=sys.stderr)
        return 3
    print("  ok — 18 slide specs, schema at #4 and #16.")

    raw = _decode_snapshot()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_bytes(raw)

    size = OUTPUT_PATH.stat().st_size
    print(f"[write] {OUTPUT_PATH.relative_to(REPO_ROOT)} ({size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
